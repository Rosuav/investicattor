let fullinvestigate = null;
on("click", "[data-investigate]", e => {
	const item = e.match.dataset.investigate;
	//Investigate an item in the current scene.
	//You can always get the basic info (even if you're out of time), but getting
	//detailed information costs time, unless you already looked at this (in which
	//case you will be shown the same info again).
	//NOTE: We assume here that there is only ever one button for a given investigation
	//target. It would be confusing for the player to have multiple anyway.
	const detail = here.investigated[item];
	replace_content(DOM("#inspectinfo"), [
		investigate_basic[state.scene][item],
		detail,
	]);
	//You can fully investigate something if there's time available (but if you already have,
	//the details are simply repeated at no time cost).
	const investigable = !enforce_time_limits || here.time_spent < loc.time_limit;
	const seen = !!detail;
	if (investigable && !seen) fullinvestigate = e.match;
	DOM("#inspect-full").hidden = seen;
	const labels = ["(out of time)", "Inspect fully", "(already accused)", "Accuse", "(no more to submit)", "Submit evidence"];
	replace_content("#inspect-full", labels[
		investigable
		+(state.accuse ? 2 : 0)
		+(state.evidence ? 2 : 0)
	]).disabled = !investigable;
	DOM("#inspectdlg").showModal();
});

on("click", "#inspect-full", e => {
	DOM("#inspectdlg").close();
	if (enforce_time_limits && here.time_spent >= loc.time_limit) return; //Shouldn't happen (the button should be hidden).
	const item = fullinvestigate.dataset.investigate;
	++here.time_spent;
	const full = investigate_full[state.scene];
	here.investigated[item] = [
		lindt.HR(),
		(full[`_${state.guilty}_${item}`] || full[item])(),
	];
	fullinvestigate.classList.add("seen");
	if (state.scene === "accuse") {
		//Autonavigate on accusation; the full-investigate info is in the Markdown scene
		state.scene = "evidence";
		state.accused = item;
		state.correct = state.accused === state.guilty;
		here = state[state.scene] = {investigated: { }, time_spent: 0};
		loc = locations[state.scene];
	}
	repaint();
	fullinvestigate.click(); //Close and re-show the dialog, now with more info.
});

