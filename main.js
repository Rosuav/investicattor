import {choc, replace_content, lindt, DOM, on, apply_fixes} from "https://rosuav.github.io/choc/factory.js";
const {BUTTON, DIALOG, DIV, H3, HEADER, P, SECTION} = lindt; //autoimport

document.body.appendChild(replace_content(null, DIALOG({id: "inspectdlg"}, SECTION([
	HEADER([H3("Inspect"), DIV([BUTTON({type: "button", class: "dialog_cancel"}, "x")])]),
	DIV({id: "inspectinfo"}, "loading..."),
	P({class: "dlgbuttonbox"}, [BUTTON({class: "dialog_close"}, "Close"), BUTTON({id: "inspect-full"}, "Inspect fully")]),
]))));
apply_fixes({close_selector: ".dialog_cancel,.dialog_close", click_outside: "formless", methods: 1});

//The content generated by Markdown is hidden in CSS, and we will generate our own main element to put our content into.
const main = document.body.appendChild(choc.MAIN({class: "main-content"}));
//Grab everything out of the Markdown main, and key it by the ID of the most recent heading.
//NOTE: If/when these get used in a replace_content call, they will be removed from their original
//place in the DOM. Don't do that with any structural elements (which should all land in markdown[""]).

function transform_links(el) {
	if (el.tagName === "A") return el.replaceWith(choc.BUTTON( //TODO: Don't do this if it's actually an external link
		{"data-investigate": el.getAttribute("href")},
		[...el.childNodes],
	));
	[...el.children].forEach(transform_links);
}

const markdown = (() => {
	const markdown = { };
	let cur = markdown[""] = [];
	for (let el = DOM("#content").firstElementChild; el; el = el.nextElementSibling) {
		if (el.tagName[0] === "H" && +el.tagName.slice(1) >= 2) //Headings at level 2 or above become new blocks
			cur = markdown[el.id] = [];
		cur.push(el);
		transform_links(el);
	}
	return markdown;
})();

const state = {scene: "intro"};

const destlabels = {
	crimescene: "The Crime Scene",
	shop: "Local shop",
	fission: "Fish-and-chippery",
};
const defaultdest = Object.keys(destlabels);

//Basic investigation info is what you can see from a cursory glance. It is unaffected by any
//form of randomization - it will be the same text every time you play the game. Further details
//can be learned by spending time.
const investigate_basic = {
	crimescene: {
		foodbowl: [
			P("An empty food bowl. I don't know how the humans expect a cat to survive without tuna."),
		],
		cupboard: [
			P("A kitchen cupboard at floor level. It's ajar; you could nudge it open with your nose if you want."),
		],
	},
	shop: {
	},
	fission: {
	},
};

//Unlike basic investigation, these are functions, and may manipulate state.
//(Decrementing time is done automatically.)
const investigate_full = {
	crimescene: {
		foodbowl: () => [
			P([
				"On closer inspection, you see dry cat food, but you can also see the bottom of the ",
				"bowl, so that means it's practically empty. The cat is literally starving, I tell you.",
			]),
		],
		cupboard: () => [
			P([
				"Inside the cupboard are various unpleasant-smelling boxes, a few old sponges that you ",
				"could tear to pieces if you wanted to make a mess, and no cans of tuna. Disappointing.",
			]),
		],
	},
	shop: {
	},
	fission: {
	},
};

function TRAVELBUTTONS(dest) {
	let have_dest = false;
	(dest||defaultdest).forEach(d => !state[d] && (have_dest = true));
	return DIV({class: "travelbuttons"}, [
		"Travel to: ",
		(dest||defaultdest).map(d => BUTTON({type: "button", "data-dest": d, disabled: !!state[d]}, destlabels[d])),
		!have_dest && BUTTON({type: "button", "data-dest": "denoument"}, "Announce your results"),
	]);
}

const scenes = {
	intro() {return [
		markdown["part-one-the-shocking-discovery"],
		TRAVELBUTTONS(["crimescene"]),
	]},
	crimescene() {return [
		markdown["part-two-the-crime-scene"],
		TRAVELBUTTONS(),
	]},
	shop() {return [
		markdown["shop"],
		TRAVELBUTTONS(),
	]},
	fission() {return [
		markdown["fish-and-chippery"],
		TRAVELBUTTONS(),
	]},
	denoument() {return [
		markdown["submit-your-findings"],
		//TODO: This is where you select a person to accuse (or "no crime happened" but maybe disable that
		//because the cat will always see that it's a crime to have no tuna), list the supporting evidence,
		//and submit the case to the human.
	]},
}

function repaint() {
	replace_content(main, scenes[state.scene]());
}
repaint();

on("click", "[data-dest]", e => {
	//Travel to a new location
	state.scene = e.match.dataset.dest;
	state[state.scene] = {investigated: { }};
	repaint();
});

let fullinvestigate = null;
on("click", "[data-investigate]", e => {
	const item = e.match.dataset.investigate;
	//Investigate an item in the current scene.
	//You can always get the basic info (even if you're out of time), but getting
	//detailed information costs time, unless you already looked at this (in which
	//case you will be shown the same info again).
	//NOTE: We assume here that there is only ever one button for a given investigation
	//target. It would be confusing for the player to have multiple anyway.
	const detail = state[state.scene].investigated[item];
	replace_content(DOM("#inspectinfo"), [
		investigate_basic[state.scene][item],
		detail,
	]);
	const seen = DOM("#inspect-full").hidden = !!detail;
	if (!seen) fullinvestigate = e.match;
	DOM("#inspectdlg").showModal();
});

on("click", "#inspect-full", e => {
	DOM("#inspectdlg").close();
	const item = fullinvestigate.dataset.investigate;
	state[state.scene].investigated[item] = [
		lindt.HR(),
		investigate_full[state.scene][item](),
	];
	fullinvestigate.classList.add("seen");
	fullinvestigate.click(); //Close and re-show the dialog, now with more info.
});
