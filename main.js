function transform_links(el) {
	if (el.tagName === "A") {
		//External links get flipped to a new tab but otherwise unchanged.
		if (el.getAttribute("href").startsWith("https://")) {
			el.target = "_blank";
			return;
		}
		return el.replaceWith(choc.BUTTON(
			{"data-investigate": el.getAttribute("href")},
			[...el.childNodes],
		));
	}
	[...el.children].forEach(transform_links);
}

const markdown = (() => {
	const markdown = { };
	let cur = markdown[""] = [];
	for (let el = DOM("#content").firstElementChild; el; el = el.nextElementSibling) {
		if (el.tagName[0] === "H" && +el.tagName.slice(1) >= 2) //Headings at level 2 or above become new blocks
			cur = markdown[el.id] = [];
		cur.push(el);
		transform_links(el);
	}
	return markdown;
})();

function random_choice(arr) {
	return arr[Math.floor(Math.random() * arr.length)];
}

